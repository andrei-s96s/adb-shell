// Лёгкий gettext-подобный механизм локализации интерфейса. Канонический
// язык приложения (русский) используется как ключ словаря перевода
// напрямую -- t('Русский текст') возвращает английский перевод, если
// currentLocale === 'en' и он есть в словаре (см. i18nDictionary.ts),
// иначе возвращает исходный текст без изменений. Такой выбор (а не
// отдельные символьные ключи вроде 'shell.broadcastButton') сильно снижает
// риск при переносе уже существующих строк по полусотне файлов: забытая
// обёртка t(...) или опечатка в словаре в худшем случае покажет русский
// текст, а не пустую строку или "[missing key]".
//
// Язык применяется целиком один раз при старте рендерера (см. bootLocale()
// в самом начале renderer.ts, до вызова любого из initXxxScreen()) --
// почти весь UI строится один раз через innerHTML/textContent при
// инициализации вкладок, а не каким-либо реактивным фреймворком, так что
// "перерисовать всё" при смене языка означало бы заново продумывать
// порядок инициализации каждого экрана. Вместо этого смена языка (сайдбар
// или Настройки, см. localeSwitch.ts) сохраняет выбор и сразу перезагружает
// окно (location.reload()) -- ощущается мгновенным, реального перезапуска
// всего приложения не требует.

import { EN_TRANSLATIONS } from './i18nDictionary.js';

export type Locale = 'ru' | 'en';

let currentLocale: Locale = 'ru';

export function setLocale(locale: Locale): void {
  currentLocale = locale;
}

export function getLocale(): Locale {
  return currentLocale;
}

/** Разделитель контекста в ключах словаря -- тот же приём, что и msgctxt в
 * gettext (pgettext): нужен там, где одна и та же русская строка должна
 * переводиться по-разному в зависимости от места (например, "Обновить" --
 * "Refresh" для списка устройств, но "Update" для установки обновления
 * APK, см. apkLibrary.ts). Обычная видимая последовательность символов
 * (не невидимый control-character) -- в реальном UI-тексте этого
 * приложения такая последовательность не встречается, а набрать её текстом
 * в словаре можно надёжно, без риска разъехаться на непечатаемый символ. */
const CONTEXT_SEPARATOR = ':::';

/** Плейсхолдеры вида {name} подставляются после выбора перевода -- словарь
 * на обоих языках должен использовать один и тот же плейсхолдер. Пропущенная
 * переменная оставляет токен как есть, а не выбрасывает исключение.
 * context -- см. CONTEXT_SEPARATOR выше; передаётся только там, где одна и
 * та же русская строка встречается в нескольких местах с разным нужным
 * переводом, в остальных случаях не нужен. */
export function t(ru: string, vars?: Record<string, string | number>, context?: string): string {
  const text =
    currentLocale === 'en'
      ? (context !== undefined ? EN_TRANSLATIONS[`${context}${CONTEXT_SEPARATOR}${ru}`] : undefined) ?? EN_TRANSLATIONS[ru] ?? ru
      : ru;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
}

/** Форматирование даты/времени (история подключений, снапшоты, журнал
 * запусков макросов и т.п.) под выбранный язык интерфейса -- Intl сам
 * знает разумный формат под каждую локаль (день/месяц/год в разном
 * порядке, 24ч vs AM/PM), явно перечислять компоненты не нужно. */
export function formatDateTime(ms: number): string {
  return new Date(ms).toLocaleString(currentLocale === 'en' ? 'en-US' : 'ru-RU');
}
