/** Максимальная задержка одного шага-паузы -- защита от опечатки в
 * миллисекундах (лишний ноль превращает "подождать 3 секунды" в "подождать
 * 3000 секунд"), а не реальное ограничение сценария использования (дождаться
 * перезагрузки устройства укладывается на порядок ниже). Проверяется и в
 * UI (macros.ts), и здесь, в исполнителе (MacroRunner.ts) -- на случай
 * макроса, импортированного из вручную отредактированного JSON. */
export const MAX_MACRO_STEP_DELAY_MS = 300_000;

export interface MacroStep {
  id: string;
  /** adb-команда без токена "adb" (например "shell pm list packages").
   * Пусто у шага-задержки (isDelay) -- у него нет команды вовсе. */
  argsLine: string;
  /** true -- шаг ничего не выполняет, только ждёт delayMs перед следующим
   * шагом. Отдельное поле, а не пустая argsLine сама по себе как признак,
   * потому что argsLine и так может быть временно пустой в процессе
   * редактирования обычного шага. Добавлено уже после того, как у всех
   * ранее сохранённых макросов этого поля не было вовсе -- отсутствующее
   * значение (undefined) корректно читается как "обычный шаг", миграция
   * данных не нужна. */
  isDelay?: boolean;
  /** Длительность паузы в мс -- имеет смысл только при isDelay === true,
   * от 0 до MAX_MACRO_STEP_DELAY_MS. */
  delayMs?: number;
  /** Условие выполнения ОБЫЧНОГО шага (isDelay !== true) относительно
   * результата ближайшего ПРЕДЫДУЩЕГО обычного шага -- задержки в подсчёте
   * "предыдущего" прозрачно пропускаются, у них нет успеха/неудачи.
   * Если такого предыдущего шага нет (это первый обычный шаг макроса) или
   * он сам был пропущен своим условием -- шаг тоже пропускается: условие
   * смотрит только на шаг непосредственно перед собой, а не ищет в глубину
   * истории по цепочке. undefined/'always' -- выполняется всегда, то же
   * поведение, что было у всех шагов до появления этого поля. */
  runIf?: 'onPreviousSuccess' | 'onPreviousFailure';
}

export interface Macro {
  id: string;
  name: string;
  steps: MacroStep[];
  /** Если true — макрос запускается автоматически, как только устройство
   * становится готовым (подключено и авторизовано). */
  autorunOnConnect: boolean;
  /** Если true — выполнение останавливается на первом же шаге, завершившемся
   * ошибкой, вместо того чтобы идти до конца. */
  abortOnFirstFailure: boolean;
  /** Глобальный хоткей (формат Electron Accelerator, например
   * "CommandOrControl+Alt+M") -- запускает макрос на устройстве из
   * hotkeySelectedSerial (main.ts, то же значение, что уже использует
   * хоткей тихого скриншота), даже когда окно не в фокусе. Макросы с
   * переменными ${ИМЯ} хоткеем не запускаются -- негде спросить их
   * значения без открытого окна. undefined/пусто — хоткей не назначен. */
  hotkeyAccelerator?: string;
  /** Пользовательские метки для группировки/фильтра макросов в списке --
   * тот же принцип, что и ApkTagStore для библиотеки APK, но живёт прямо на
   * самом макросе, а не в отдельном хранилище "путь -> теги": у макроса,
   * в отличие от файла на диске, и так уже есть стабильный id и полноценная
   * запись в MacroStore. undefined/пустой массив — тегов нет. */
  tags?: string[];
}

export interface MacroRunResult {
  argsLine: string;
  output: string;
  isError: boolean;
  /** true -- шаг не выполнялся: его условие runIf не выполнилось
   * относительно предыдущего шага. Намеренно НЕ считается ошибкой --
   * abortOnFirstFailure это не прерывает, это ожидаемый, а не аварийный
   * исход. */
  skipped?: boolean;
}
